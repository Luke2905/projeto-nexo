import { createHash } from "node:crypto";
import { createWriteStream } from "node:fs";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { pipeline } from "node:stream/promises";
import { Readable } from "node:stream";
import { spawnSync } from "node:child_process";
import { gzipSync } from "node:zlib";
import pt from "dictionary-pt";
import { DAILY_CATALOG_V3 } from "../server/game/dailyCatalogV3.ts";

const MODEL = "nilc-nlp/glove-50d";
const MODEL_REVISION = "9296f6537f6b0a24d449a2677c21c18c2c0c3bdd";
const MODEL_BYTES = 185_921_088;
const VOCABULARY_LIMIT = 20_000;
const NEIGHBOR_LIMIT = 2_048;
const output = new URL("../server/game/generated/semantic-ranks.ts", import.meta.url);
const worker = new URL("./build-semantic-ranks.py", import.meta.url);

const signatureSources = [
  new URL(import.meta.url),
  worker,
  new URL("../server/game/dailyCatalogV3.ts", import.meta.url),
  new URL("../server/game/expandedCatalog.ts", import.meta.url),
  new URL("../server/game/dailyCatalogV2.ts", import.meta.url),
  new URL("../server/game/dictionary.ts", import.meta.url),
];
const signatureHash = createHash("sha256");
for (const source of signatureSources) {
  const normalizedSource = (await readFile(source, "utf8")).replace(/\r\n/g, "\n");
  signatureHash.update(normalizedSource);
}
signatureHash.update(`${MODEL}/${MODEL_REVISION}/${VOCABULARY_LIMIT}/${NEIGHBOR_LIMIT}`);
const signature = signatureHash.digest("hex");
const header = `// Generated by scripts/build-semantic-ranks.mjs from ${MODEL} (${MODEL_REVISION}).\n// ${signature}\n`;

try {
  const currentOutput = (await readFile(output, "utf8")).replace(/\r\n/g, "\n");
  if (currentOutput.startsWith(header)) {
    console.log("Portuguese semantic ranks are up to date.");
    process.exit(0);
  }
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}

function normalize(value) {
  return value.trim().toLocaleLowerCase("pt-BR").normalize("NFD").replace(/[\u0300-\u036f]/g, "");
}

const stopwords = new Set([
  "a", "ao", "aos", "aquela", "aquele", "aqueles", "as", "ate", "com", "como", "da", "das",
  "de", "dela", "dele", "do", "dos", "e", "ela", "elas", "ele", "eles", "em", "entre", "era",
  "essa", "esse", "esta", "este", "eu", "foi", "ha", "isso", "isto", "ja", "lhe", "mais", "mas",
  "me", "mesmo", "meu", "minha", "muito", "na", "nao", "nas", "nem", "no", "nos", "nossa",
  "o", "os", "ou", "para", "pela", "pelo", "por", "qual", "que", "se", "sem", "seu", "sua",
  "tambem", "tem", "ter", "teu", "tua", "um", "uma", "voce",
]);

const baseWords = new Set(
  pt.dic.toString().split(/\r?\n/).slice(1)
    .map(line => normalize(line.split("/")[0]))
    .filter(word => /^[a-z]{3,25}$/.test(word)),
);

const vocabUrl = `https://huggingface.co/${MODEL}/resolve/${MODEL_REVISION}/vocab.txt`;
const modelUrl = `https://huggingface.co/${MODEL}/resolve/${MODEL_REVISION}/embeddings.safetensors`;
const modelVocabulary = (await (await fetch(vocabUrl)).text()).split(/\r?\n/).filter(Boolean);
const modelIndex = new Map();
for (let index = 0; index < modelVocabulary.length; index++) {
  const raw = modelVocabulary[index];
  if (raw !== raw.toLocaleLowerCase("pt-BR")) continue;
  const word = normalize(raw);
  if (/^[a-z]{2,25}$/.test(word) && !modelIndex.has(word)) modelIndex.set(word, index);
}

const selected = [];
const selectedSet = new Set();
for (const raw of modelVocabulary) {
  if (selected.length >= VOCABULARY_LIMIT) break;
  const word = normalize(raw);
  if (
    !selectedSet.has(word) &&
    baseWords.has(word) &&
    !stopwords.has(word) &&
    /^[a-z]{3,25}$/.test(word)
  ) {
    selected.push(word);
    selectedSet.add(word);
  }
}

const requiredTerms = DAILY_CATALOG_V3.flatMap(entry => [entry.word, ...Object.keys(entry.aliases)])
  .filter(term => !term.includes(" "))
  .map(normalize);
for (const word of requiredTerms) {
  if (!selectedSet.has(word) && modelIndex.has(word)) {
    selected.push(word);
    selectedSet.add(word);
  }
}

const missingTargets = DAILY_CATALOG_V3.map(entry => normalize(entry.word)).filter(word => !modelIndex.has(word));
if (missingTargets.length) throw new Error(`Embedding model is missing targets: ${missingTargets.join(", ")}`);
if (selected.length >= 65_536) throw new Error("Semantic vocabulary exceeds uint16 capacity");

selected.sort();
const targetWords = DAILY_CATALOG_V3.map(entry => normalize(entry.word)).sort();
const vocabularyIndices = selected.map(word => modelIndex.get(word));
const targetIndices = targetWords.map(word => modelIndex.get(word));

const cacheDir = path.join(tmpdir(), "nexo-semantic-cache");
await mkdir(cacheDir, { recursive: true });
const modelPath = path.join(cacheDir, `glove-50d-${MODEL_REVISION}.safetensors`);
let modelReady = false;
try {
  modelReady = (await stat(modelPath)).size === MODEL_BYTES;
} catch {}
if (!modelReady) {
  console.log(`Downloading ${MODEL} (${Math.round(MODEL_BYTES / 1024 / 1024)} MiB)...`);
  const response = await fetch(modelUrl);
  if (!response.ok || !response.body) throw new Error(`Model download failed: ${response.status}`);
  await pipeline(Readable.fromWeb(response.body), createWriteStream(modelPath));
  if ((await stat(modelPath)).size !== MODEL_BYTES) throw new Error("Downloaded model has an unexpected size");
}

const metadataPath = path.join(cacheDir, `semantic-${signature}.json`);
const ranksPath = path.join(cacheDir, `semantic-${signature}.bin`);
await writeFile(metadataPath, JSON.stringify({
  vocabulary_indices: vocabularyIndices,
  target_indices: targetIndices,
  neighbor_limit: NEIGHBOR_LIMIT,
}));
const result = spawnSync("python", [worker.pathname.slice(1), modelPath, metadataPath, ranksPath], {
  stdio: "inherit",
});
if (result.status !== 0) throw new Error(`Semantic rank worker failed with exit code ${result.status}`);

const ranks = await readFile(ranksPath);
const expectedBytes = targetWords.length * NEIGHBOR_LIMIT * 2;
if (ranks.length !== expectedBytes) throw new Error(`Unexpected semantic rank size: ${ranks.length}`);

const wordsCompressed = gzipSync(selected.join("\n"), { level: 9 }).toString("base64");
const targetsCompressed = gzipSync(targetWords.join("\n"), { level: 9 }).toString("base64");
const ranksCompressed = gzipSync(ranks, { level: 9 }).toString("base64");
await mkdir(new URL("../server/game/generated/", import.meta.url), { recursive: true });
await writeFile(output, header + [
  `export const SEMANTIC_VOCABULARY_SIZE = ${selected.length};`,
  `export const SEMANTIC_NEIGHBOR_LIMIT = ${NEIGHBOR_LIMIT};`,
  `export const semanticWords = ${JSON.stringify(wordsCompressed)};`,
  `export const semanticTargets = ${JSON.stringify(targetsCompressed)};`,
  `export default ${JSON.stringify(ranksCompressed)};`,
  "",
].join("\n"));
console.log(`Semantic ranks: ${targetWords.length} targets, ${selected.length} words, ${Math.round(ranksCompressed.length / 1024)} KiB bundled.`);
